def is_ad(title):
    """判断是否为广告/无关内容"""
    for kw in AD_KEYWORDS:
        if kw in title:
            return True
    return False

def categorize(title, default_category):
    """对新闻标题进行运动分类"""
    for sport, kws in SPORT_KEYWORDS.items():
        for kw in kws:
            if kw in title:
                return sport
    return default_category

def fetch_url(url, timeout=12):
    """抓取网页内容"""
    try:
        req = urllib.request.Request(url, headers={
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
            'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
            'Accept-Language': 'zh-CN,zh;q=0.9,en;q=0.8',
            'Accept-Encoding': 'identity',
            'Connection': 'keep-alive',
        })
        resp = urllib.request.urlopen(req, timeout=timeout)
        return resp.read().decode('utf-8', errors='ignore')
    except Exception as e:
        print(f"  抓取失败 {url}: {e}")
        return ''

def extract_news_from_html(html, source_name, default_category):
    """从HTML中提取新闻链接"""
    news = []
    seen_urls = set()
    seen_titles = set()
    
    # 匹配新浪体育新闻链接
    pattern = r'<a[^>]+href="(https?://sports\.sina\.com\.cn/[^"]+\.s?html?)"[^>]*>([^<]{8,80})</a>'
    matches = re.findall(pattern, html)
    
    for url, title in matches:
        title = unescape(title.strip())
        # 过滤
        if not title or len(title) < 8 or len(title) > 80:
            continue
        if is_ad(title):
            continue
        if url in seen_urls or title in seen_titles:
            continue
        seen_urls.add(url)
        seen_titles.add(title)
        
        category = categorize(title, default_category)
        news.append({
            'id': 'rt_' + str(int(datetime.now().timestamp() * 1000)) + '_' + str(len(news)),
            'category': category,
            'title': title,
            'content': title,
            'source': source_name,
            'source_url': url,
            'time': datetime.now().strftime('%Y年%m月%d日 %H:%M'),
            'realtime': True
        })
    
    return news[:50]  # 每个源限制前50条

def main():
    """主函数：抓取所有新闻源并保存"""
    all_news = []
    total_by_source = {}
    
    print(f"=== Overtime 新闻抓取开始: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} ===")
    
    for source in NEWS_SOURCES:
        print(f"\n抓取 {source['name']} ({source['url']})...")
        html = fetch_url(source['url'])
        if not html:
            total_by_source[source['name']] = 0
            continue
        
        news = extract_news_from_html(html, source['name'], source['category'])
        total_by_source[source['name']] = len(news)
        all_news.extend(news)
        print(f"  获取 {len(news)} 条新闻")
    
    # 去重（按标题）
    seen = set()
    unique_news = []
    for n in all_news:
        if n['title'] not in seen:
            seen.add(n['title'])
            unique_news.append(n)
    
    # 按分类统计
    category_count = {}
    for n in unique_news:
        cat = n['category']
        category_count[cat] = category_count.get(cat, 0) + 1
    
    print(f"\n=== 抓取完成 ===")
    print(f"总计: {len(unique_news)} 条唯一新闻")
    print(f"分类统计: {json.dumps(category_count, ensure_ascii=False)}")
    print(f"来源统计: {json.dumps(total_by_source, ensure_ascii=False)}")
    
    # 保存
    output = {
        'fetch_time': datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
        'fetch_timestamp': int(datetime.now().timestamp()),
        'count': len(unique_news),
        'category_count': category_count,
        'source_count': total_by_source,
        'news': unique_news
    }
    
    # 确保输出目录存在
    output_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, 'realtime_news.json')
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(output, f, ensure_ascii=False, indent=2)
    
    print(f"\n已保存到: {output_path}")
    print(f"文件大小: {os.path.getsize(output_path)} bytes")
    
    # 打印前15条新闻
    print(f"\n=== 最新15条新闻 ===")
    for i, n in enumerate(unique_news[:15]):
        print(f"  {i+1}. [{n['category']}] {n['title'][:60]}")

if __name__ == '__main__':
    main()
